export const PREF_COUNT = PREFS.length;
export const prefByCode = (code: number): Pref | undefined => PREFS.find((p) => p.code === code);
export const prefById = (id: string): Pref | undefined => PREFS.find((p) => p.id === id);

export interface MapState {
  /** 何周目か(1から)。47県ぬり終えたら次の1つ目で2周目になり、地図は白にもどる */
  round: number;
  /** 今の周でぬり終えたコード(ぬった順) */
  filled: number[];
  /** 次にぬる県(いまの周が終わっていて、次が新しい周の1つ目ならその県) */
  next: Pref;
  /** 今の周を全部ぬり終えた状態(次のごほうびで白にもどる) */
  complete: boolean;
}

/** ぬる順は常に コード1→47。記録の数だけ進む */
export function mapState(log: Pick<MapGet, 'prefCode'>[]): MapState {
  const n = log.length;
  const filledCount = n === 0 ? 0 : ((n - 1) % PREF_COUNT) + 1;
  const round = n === 0 ? 1 : Math.floor((n - 1) / PREF_COUNT) + 1;
  return {
    round,
    filled: PREFS.slice(0, filledCount).map((p) => p.code),
    next: PREFS[n % PREF_COUNT],
    complete: n > 0 && n % PREF_COUNT === 0,
  };
}

/** 次にもらう県を決めて、記録に足す形にする(コードは必ず mapState の next に合わせる) */
export function nextGet(log: Pick<MapGet, 'prefCode'>[]): number {
  return mapState(log).next.code;
}

